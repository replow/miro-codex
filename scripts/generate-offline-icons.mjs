import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoots = ['src', 'config'];
const extensions = new Set(['.astro', '.md', '.mdx', '.ts', '.tsx', '.yaml', '.yml']);
const idPattern = /(?<![\w-])([a-z0-9-]+):([a-z0-9-]+)(?![\w-])/g;
const ids = new Set();

function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      scan(fullPath);
      continue;
    }

    if (!extensions.has(path.extname(entry.name))) continue;
    const content = fs.readFileSync(fullPath, 'utf8');
    for (const match of content.matchAll(idPattern)) ids.add(`${match[1]}:${match[2]}`);
  }
}

for (const sourceRoot of sourceRoots) scan(path.join(root, sourceRoot));

const icons = {};
const missing = [];

for (const id of [...ids].sort()) {
  const [prefix, name] = id.split(':');
  const iconSetPath = path.join(root, 'node_modules', '@iconify-json', prefix, 'icons.json');
  if (!fs.existsSync(iconSetPath)) continue;

  const iconSet = JSON.parse(fs.readFileSync(iconSetPath, 'utf8'));
  const icon = iconSet.icons[name];
  if (!icon) {
    missing.push(id);
    continue;
  }

  icons[id] = {
    width: icon.width ?? iconSet.width ?? 24,
    height: icon.height ?? iconSet.height ?? 24,
    ...(icon.rotate === undefined ? {} : { rotate: icon.rotate }),
    ...(icon.hFlip ? { hFlip: true } : {}),
    ...(icon.vFlip ? { vFlip: true } : {}),
    body: icon.body,
  };
}

const output = [
  '// Generated by scripts/generate-offline-icons.mjs. Do not edit manually.',
  "import type { IconifyIcon } from '@iconify/react';",
  '',
  'export const offlineIcons: Record<string, IconifyIcon> = ',
  `${JSON.stringify(icons, null, 2)};`,
  '',
].join('\n');

fs.writeFileSync(path.join(root, 'src', 'lib', 'offline-icons.ts'), output);
console.log(`Generated ${Object.keys(icons).length} local icons.`);
if (missing.length > 0) console.warn(`Unresolved icon names: ${missing.join(', ')}`);
